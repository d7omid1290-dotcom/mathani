def quote(k, phrase):
    disp = data["verses"][k]["t"]
    # نفس tokens في core.js: إلحاق علامات الوقف بالكلمة السابقة
    toks, pre = [], ""
    for w in disp.split():
        if not norm(w):
            if toks: toks[-1] += " " + w
            else: pre += w + " "
        else: toks.append(pre + w); pre = ""
    n = [norm(t)[0] for t in toks]; q = phrase.split()
    for i in range(len(n) - len(q) + 1):
        if n[i:i+len(q)] == q: return " ".join(toks[i:i+len(q)])
    raise SystemExit(f"الاقتباس غير موجود في {k}: {phrase}")

